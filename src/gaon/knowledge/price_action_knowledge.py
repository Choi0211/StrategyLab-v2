@dataclass(frozen=True)
class ContextualSetupSpec:
    """One Contextual Setup: market regime + structure + location + signal
    candle + confirmation. This is the only shape a hypothesis may take in
    this module - never a bare "pattern implies direction" rule."""

    setup_id: str
    market: PriceActionMarket
    regime: str
    structure: str
    location: str
    signal_candle: str
    confirmation: str
    concept_ids: tuple[str, ...]
    bin_pa_family: str | None = None

    def __post_init__(self) -> None:
        for concept_id in self.concept_ids:
            if concept_id not in _ALL_CONCEPTS:
                raise ValueError(f"unknown price-action concept_id: {concept_id}")

    @property
    def topic_key(self) -> str:
        return f"priceaction.{self.market.value}.{self.setup_id}"

    def description_sentences(self) -> tuple[str, ...]:
        """Verbatim-extractable sentences describing this setup. Every
        sentence is source text handed to the real claim extractor - not a
        performance claim, and it contains no percentage or metric token."""
        sentences = [
            f"Contextual Setup {self.setup_id}: within a {self.regime}, this setup requires {self.structure}.",
            f"The setup looks for this structure at {self.location}.",
            f"The signal candle for this setup is {self.signal_candle}.",
            f"Confirmation for this setup is {self.confirmation}.",
        ]
        for concept_id in self.concept_ids:
            sentences.append(_ALL_CONCEPTS[concept_id].definition)
        return tuple(sentences)

    def to_json(self) -> dict[str, object]:
        return {
            "setup_id": self.setup_id,
            "market": self.market.value,
            "topic_key": self.topic_key,
            "regime": self.regime,
            "structure": self.structure,
            "location": self.location,
            "signal_candle": self.signal_candle,
            "confirmation": self.confirmation,
            "concept_ids": list(self.concept_ids),
            "bin_pa_family": self.bin_pa_family,
        }


def build_contextual_setup(
    *,
    setup_id: str,
    market: PriceActionMarket,
    regime: str,
    structure: str,
    location: str,
    signal_candle: str,
    confirmation: str,
    concept_ids: tuple[str, ...],
    bin_pa_family: str | None = None,
) -> ContextualSetupSpec:
    """Reusable combinator: mints ONE new Contextual Setup from a
    regime/structure/location/signal/confirmation permutation drawn from the
    NISON_CONCEPTS/BROOKS_CONCEPTS catalog.

    This is the actual "Strategy Hypothesis Generator" input surface: any
    caller (a human, or a future Gaon research-director combinatorial
    expansion step) can call this with a NEW permutation not present in
    BINANCE_CONTEXTUAL_SETUPS below, then pass the result through
    seed_price_action_hypothesis() to mint a real, evidence-backed,
    PROPOSED hypothesis via the existing EvidenceBackedHypothesisGenerator -
    the seed list below is a starting set, not the ceiling of what this
    surface can produce.
    """
    return ContextualSetupSpec(
        setup_id=setup_id, market=market, regime=regime, structure=structure, location=location,
        signal_candle=signal_candle, confirmation=confirmation, concept_ids=concept_ids,
        bin_pa_family=bin_pa_family,
    )


