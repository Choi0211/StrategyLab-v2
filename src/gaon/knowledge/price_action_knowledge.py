def _book_source(*, title: str, locator: str, text: str, author: str) -> SourceProvenance:
    return SourceProvenance.create(
        source_type=SourceType.BOOK,
        title=title,
        locator=locator,
        content_sha256=hashlib.sha256(text.encode("utf-8")).hexdigest(),
        trust_level=TrustLevel.HIGH,
        author=author,
        publisher="price-action-knowledge-seed",
        published_at="1991-01-01" if author == "Steve Nison" else "2009-01-01",
        license_name="research-reference-only",
        ingested_at="2026-08-23T00:00:00+00:00",
    )


def seed_price_action_hypothesis(
    setup: ContextualSetupSpec,
    *,
    storage: GaonStorage,
) -> EvidenceBackedStrategyHypothesis:
    """Runs ONE Contextual Setup through the real pipeline: SourceProvenance
    -> AutonomousKnowledgeResearchLoop (verbatim claim extraction) ->
    ExternalResearchMemoryStore (persisted, deduplicated) ->
    EvidenceBackedHypothesisGenerator. Returns the resulting PROPOSED
    hypothesis. Raises if the pipeline blocks at any stage (e.g. a
    fabricated-metric token slipped into a setup's text) - a silent
    fallback here would risk seeding knowledge that only looks
    evidence-backed."""
    author = "Al Brooks" if any(_ALL_CONCEPTS[cid].author == "brooks" for cid in setup.concept_ids) else "Steve Nison"
    content_text = " ".join(setup.description_sentences())
    source = _book_source(
        title=f"Contextual Setup seed: {setup.setup_id}",
        locator=f"https://example.invalid/price-action-knowledge-seed/{setup.topic_key}",
        text=content_text,
        author=author,
    )
    loop = AutonomousKnowledgeResearchLoop().run(
        topic_key=setup.topic_key,
        evidence=(SourceEvidenceInput(source, content_text.encode("utf-8"), "text/plain", ClaimStance.SUPPORTS),),
    )

    store = ExternalResearchMemoryStore(storage)
    write_result = store.add_loop_result(loop, created_at="2026-08-23T00:00:00+00:00")
    if write_result.status not in (ExternalResearchMemoryStatus.STORED, ExternalResearchMemoryStatus.DUPLICATE):
        raise RuntimeError(
            f"price-action knowledge seed blocked for {setup.topic_key}: {write_result.blockers}"
        )
    record = write_result.record or store.find_by_fingerprint(external_research_memory_fingerprint(loop))

    generator = EvidenceBackedHypothesisGenerator()
    hypothesis = generator.generate(
        topic_key=setup.topic_key,
        memories=(record,),
        changed_rules=(
            f"Enter only when {setup.structure}, at {setup.location}, confirmed by {setup.signal_candle}, with "
            f"{setup.confirmation}.",
        ),
        rationale=(
            f"This Contextual Setup combines a {setup.regime} with {setup.structure} at {setup.location}, "
            "rather than treating the signal candle as meaningful on its own."
        ),
        mechanism=(
            f"Entry only triggers once the signal candle ({setup.signal_candle}) appears and {setup.confirmation}; "
            "the surrounding regime and structure are prerequisites, not optional context."
        ),
        falsification_criteria=(
            "Reject this hypothesis if independent out-of-sample research evidence does not show the combined "
            "setup outperforming the signal candle alone, evaluated separately per market.",
        ),
    )
    if hypothesis.status is not StrategyHypothesisStatus.PROPOSED:
        raise RuntimeError(f"price-action hypothesis for {setup.topic_key} was blocked: {hypothesis.blockers}")
    return hypothesis


def seed_binance_price_action_hypotheses(
    *,
    storage: GaonStorage,
) -> tuple[EvidenceBackedStrategyHypothesis, ...]:
    """Seeds every BINANCE_CONTEXTUAL_SETUPS entry as a real, evidence-backed
    PROPOSED hypothesis. Never touches a KR-scoped topic_key."""
    hypotheses = []
    for setup in BINANCE_CONTEXTUAL_SETUPS:
        assert setup.market is PriceActionMarket.BINANCE, "this seed function is BINANCE-only by construction"
        hypotheses.append(seed_price_action_hypothesis(setup, storage=storage))
    return tuple(hypotheses)


def production_price_action_knowledge_seed_release_check() -> Mapping[str, object]:
    """Regression guard: seeding produces one PROPOSED, evidence-backed
    hypothesis per Binance Contextual Setup, none carry a fabricated
    performance metric, all are correctly market-namespaced, at least one
    setup is a genuinely new combination not mapped to any existing BIN-PA
    family, and no promotion/order/mutation invariant is touched."""
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        storage = GaonStorage(tmp)
        hypotheses = seed_binance_price_action_hypotheses(storage=storage)

    all_proposed = all(h.status is StrategyHypothesisStatus.PROPOSED for h in hypotheses)
    all_binance_scoped = all(h.topic_key.startswith("priceaction.binance.") for h in hypotheses)
    no_kr_topic = all("priceaction.kr." not in h.topic_key for h in hypotheses)
    all_evidence_linked = all(len(h.claim_ids) > 0 and len(h.evidence_memory_ids) > 0 for h in hypotheses)
    none_tested_or_validated = all(
        not h.tested and not h.knowledge_validated and not h.production_approved and not h.policy_applied
        for h in hypotheses
    )
    none_mutate_or_trade = all(not h.strategy_mutated and not h.order_executed for h in hypotheses)
    covers_nison_and_brooks_families = (
        any(s.bin_pa_family == "BIN-PA-01" for s in BINANCE_CONTEXTUAL_SETUPS)
        and any(s.bin_pa_family == "BIN-PA-02" for s in BINANCE_CONTEXTUAL_SETUPS)
        and any(s.bin_pa_family == "BIN-PA-03" for s in BINANCE_CONTEXTUAL_SETUPS)
        and any(s.bin_pa_family == "BIN-PA-04" for s in BINANCE_CONTEXTUAL_SETUPS)
    )
    has_novel_combination = any(s.bin_pa_family is None for s in BINANCE_CONTEXTUAL_SETUPS)
    unique_hypothesis_ids = len({h.hypothesis_id for h in hypotheses}) == len(hypotheses)

    checks = {
        "seeded_all_setups": len(hypotheses) == len(BINANCE_CONTEXTUAL_SETUPS),
        "all_proposed": all_proposed,
        "all_binance_scoped": all_binance_scoped,
        "no_kr_topic_present": no_kr_topic,
        "all_evidence_linked": all_evidence_linked,
        "none_tested_or_validated": none_tested_or_validated,
        "none_mutate_or_trade": none_mutate_or_trade,
        "covers_all_four_bin_pa_families": covers_nison_and_brooks_families,
        "has_novel_non_bin_pa_combination": has_novel_combination,
        "unique_hypothesis_ids": unique_hypothesis_ids,
    }
    if not all(checks.values()):
        failed = ",".join(name for name, ok in checks.items() if not ok)
        raise RuntimeError(f"price-action knowledge seed release check failed: {failed}")

    return {
        "schema_version": PRICE_ACTION_KNOWLEDGE_SCHEMA_VERSION,
        **checks,
        "seeded_count": len(hypotheses),
        "strategy_mutated": False,
        "order_executed": False,
        "champion_promoted": False,
        "approval_bypassed": False,
        "safety": "pass",
    }
