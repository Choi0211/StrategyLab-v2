"""Price-action Research Memory seed: Nison / Brooks Contextual Setups.

Seeds Gaon's evidence-backed Research Memory (see `external_research_memory.py`
and `evidence_hypothesis.py`) with structured, evidence-backed hypotheses
derived from candlestick-analysis concepts commonly associated with Steve
Nison and price-action concepts commonly associated with Al Brooks.

This module does NOT invent a parallel knowledge store. Every hypothesis it
produces is generated by running the SAME real pipeline every other piece of
external research in this codebase uses: SourceProvenance -> a bounded
AutonomousKnowledgeResearchLoop (verbatim sentence-level claim extraction,
no LLM, no paraphrase) -> ExternalResearchMemoryStore -> the existing
EvidenceBackedHypothesisGenerator. This module supplies the domain content
and the market-scoping convention on top of that pipeline; it does not
reimplement any part of it.

Deliberately excluded, per explicit product requirement: a bare rule like
"Hammer = BUY" is never stored. Every hypothesis is a Contextual Setup - a
combination of market regime + structure + location + signal candle +
confirmation - never an isolated candle-pattern fact.

Market isolation: `PriceActionMarket` scopes every seeded hypothesis to
exactly one market via the topic_key namespace
("priceaction.<market>.<setup_id>"). Performance evidence for one market must
never be attached to, or presented as applying to, a hypothesis scoped to a
different market. This module only seeds BINANCE-scoped hypotheses (the four
already-implemented BIN-PA-01..04 research families in the sibling
binance_ai_bot_2 project are Contextual Setups in exactly this shape); the
same `build_contextual_setup`/seeding path works unchanged for a future KR
seed list under the "priceaction.kr.*" namespace.

Safety invariants (same as every module in this package):
- every hypothesis is PROPOSED (evidence-backed, unvalidated), never a
  validated/approved/tested claim
- no fabricated performance metric is stored (enforced by the existing
  _FORBIDDEN_PERFORMANCE_TOKENS check in evidence_hypothesis.py; this module
  never writes a percentage or a metric-shaped token into hypothesis text)
- no strategy mutation, Champion promotion, approval bypass, or trading
"""

